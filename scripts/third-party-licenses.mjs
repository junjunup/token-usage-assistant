// Third-party license texts shipped with the app (T8.7). Writes THIRD_PARTY_LICENSES.txt from the installed packages
// that end up in dist/client (found with a sourcemap build, 2026-10-23) plus the two Geist font packages.
// Electron's own licenses ship separately (LICENSE.electron.txt, LICENSES.chromium.html).
//   node scripts/third-party-licenses.mjs          write the file
//   node scripts/third-party-licenses.mjs --check  exit 1 when the file is out of date (versions or texts changed)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'THIRD_PARTY_LICENSES.txt');
// [package, the direct dependency whose pnpm folder holds it (null = direct)]
export const BUNDLED = [
  ['react', null],
  ['react-dom', null],
  ['scheduler', 'react-dom'],
  ['chart.js', null],
  ['@kurkle/color', 'chart.js'],
  ['@phosphor-icons/react', null],
  ['@fontsource/geist', null],
  ['@fontsource/geist-mono', null],
];

function packageDir(name, via) {
  if (!via) return fs.realpathSync(path.join(ROOT, 'node_modules', name));
  // pnpm: .pnpm/<via>@<v>/node_modules/<via> -> its sibling node_modules/<name>
  const viaDir = fs.realpathSync(path.join(ROOT, 'node_modules', via));
  const modules = via.startsWith('@') ? path.resolve(viaDir, '..', '..') : path.resolve(viaDir, '..');
  return fs.realpathSync(path.join(modules, name));
}

export function render() {
  const parts = [
    'Token 用量助手 — third-party licenses',
    '',
    'This file lists the open-source components bundled into the app and the full text of their licenses.',
    'Electron, Chromium and Node.js: see LICENSE.electron.txt and LICENSES.chromium.html (Windows: the install folder; macOS: Contents/Resources).',
    'Generated by scripts/third-party-licenses.mjs from the installed packages; do not edit by hand.',
    '',
  ];
  for (const [name, via] of BUNDLED) {
    const dir = packageDir(name, via);
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const file = fs.readdirSync(dir).find((f) => /^licen[cs]e(\.(md|txt))?$/i.test(f));
    if (!file) throw new Error(`No license file in ${name}`);
    const text = fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim();
    parts.push('='.repeat(78), `${name} ${pkg.version} (${pkg.license})`, '='.repeat(78), '', text, '');
  }
  return parts.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('THIRD_PARTY_LICENSES.txt is out of date: run node scripts/third-party-licenses.mjs');
      process.exit(1);
    }
  } else fs.writeFileSync(OUT, text);
}
